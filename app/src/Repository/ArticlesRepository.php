    public function findByTitle(string $query): ?array
    {
        return $this->createQueryBuilder('a')
            ->where('LOWER(a.title) LIKE LOWER(:q)')
            ->setParameter('q', '%' . $query . '%')
            ->getQuery()
            ->getResult();
